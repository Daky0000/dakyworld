function schemaFor(page, title, description) {
  const url = `${ORIGIN}${page.path}`;
  const graph = [];

  for (const kind of page.schema ?? []) {
    if (kind === "organization") graph.push(organisation);
    if (kind === "website") graph.push(website);
    if (kind === "localbusiness") graph.push(localBusiness);
    if (kind === "services") {
      graph.push({
        "@type": "OfferCatalog",
        "@id": `${url}#catalogue`,
        name: "What Dakyworld covers",
        url,
        provider: { "@id": `${ORIGIN}/#organization` },
        itemListElement: SERVICE_CATALOGUE.map(([name, text], index) => ({
          "@type": "Offer",
          position: index + 1,
          itemOffered: { "@type": "Service", name, description: text, provider: { "@id": `${ORIGIN}/#organization` } },
        })),
      });
    }
    if (kind === "service" && page.service) {
      graph.push({
        "@type": "Service",
        "@id": `${url}#service`,
        name: page.service.name,
        description: page.service.description,
        url,
        serviceType: "Information technology services",
        provider: { "@id": `${ORIGIN}/#organization` },
        areaServed: [
          { "@type": "Country", name: "Ghana" },
          { "@type": "Place", name: "West Africa" },
        ],
      });
    }
    if (kind === "blog") {
      graph.push({ "@type": "Blog", "@id": `${url}#blog`, url, name: title, description, publisher: { "@id": `${ORIGIN}/#organization` }, inLanguage: "en-GB" });
    }
    if (kind === "contact") {
      graph.push({ "@type": "ContactPage", "@id": `${url}#page`, url, name: title, description, isPartOf: { "@id": `${ORIGIN}/#website` } });
    }
    if (kind === "about") {
      graph.push({ "@type": "AboutPage", "@id": `${url}#page`, url, name: title, description, isPartOf: { "@id": `${ORIGIN}/#website` }, about: { "@id": `${ORIGIN}/#organization` } });
    }
    if (kind === "collection") {
      graph.push({ "@type": "CollectionPage", "@id": `${url}#page`, url, name: title, description, isPartOf: { "@id": `${ORIGIN}/#website` } });
    }
    if (kind === "webpage") {
      graph.push({ "@type": "WebPage", "@id": `${url}#page`, url, name: title, description, isPartOf: { "@id": `${ORIGIN}/#website` } });
    }
  }

  if (page.breadcrumb?.length) {
    graph.push({
      "@type": "BreadcrumbList",
      "@id": `${url}#breadcrumb`,
      itemListElement: [["Home", "/"], ...page.breadcrumb].map(([name, href], index) => ({
        "@type": "ListItem",
        position: index + 1,
        name,
        item: `${ORIGIN}${href === "/" ? "/" : href}`,
      })),
    });
  }

  return { "@context": "https://schema.org", "@graph": graph };
}

// --- the block that goes into each head ---------------------------------------

function headBlock(page, title, description) {
  const url = `${ORIGIN}${page.path}`;
  const json = JSON.stringify(schemaFor(page, title, description), null, 2);

  return [
    BEGIN,
    `<link rel="canonical" href="${url}">`,
    `<meta name="robots" content="index, follow, max-image-preview:large, max-snippet:-1, max-video-preview:-1">`,
    `<meta name="keywords" content="${attr(page.keywords)}">`,
    `<meta name="author" content="${COMPANY.name}">`,
    `<meta name="geo.region" content="GH-AH">`,
    `<meta name="geo.placename" content="${COMPANY.locality}">`,
    ...(VERIFICATION.google ? [`<meta name="google-site-verification" content="${attr(VERIFICATION.google)}">`] : []),
    ...(VERIFICATION.bing ? [`<meta name="msvalidate.01" content="${attr(VERIFICATION.bing)}">`] : []),
    ``,
    `<meta property="og:type" content="website">`,
    `<meta property="og:site_name" content="${COMPANY.name}">`,
    `<meta property="og:locale" content="en_GB">`,
    `<meta property="og:url" content="${url}">`,
    `<meta property="og:title" content="${attr(title)}">`,
    `<meta property="og:description" content="${attr(description)}">`,
    `<meta property="og:image" content="${SHARE_IMAGE}">`,
    `<meta property="og:image:width" content="1200">`,
    `<meta property="og:image:height" content="630">`,
    `<meta property="og:image:type" content="image/png">`,
    `<meta property="og:image:alt" content="${attr(SHARE_IMAGE_ALT)}">`,
    ``,
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:title" content="${attr(title)}">`,
    `<meta name="twitter:description" content="${attr(description)}">`,
    `<meta name="twitter:image" content="${SHARE_IMAGE}">`,
    `<meta name="twitter:image:alt" content="${attr(SHARE_IMAGE_ALT)}">`,
    ``,
    `<script type="application/ld+json">`,
    json,
    `</script>`,
    ``,
    `<!-- Does nothing until the GA4 Measurement ID is filled in at the top of that file. -->`,
    `<script src="/assets/analytics.js" defer></script>`,
    END,
  ].join("\n");
}

/** Everything this generator owns is inside the markers, plus the old stray canonical it replaces. */
function applyTo(html, block) {
  let next = html;

  const begin = next.indexOf(BEGIN);
  if (begin !== -1) {
    const end = next.indexOf(END, begin);
    next = next.slice(0, begin) + block + next.slice(end + END.length);
    return next;
  }

  // First run: drop any hand-written canonical, then insert after the title.
  next = next.replace(/^[ \t]*<link rel="canonical"[^>]*>\r?\n/m, "");
  const titleEnd = next.indexOf("</title>");
  if (titleEnd === -1) throw new Error("no <title> to anchor to");
  const at = titleEnd + "</title>".length;
  return `${next.slice(0, at)}\n${block}${next.slice(at)}`;
}

// --- run ----------------------------------------------------------------------

const check = process.argv.includes("--check");
const stale = [];

for (const page of PAGES) {
  const html = readFileSync(page.file, "utf8");
  const rawTitle = between(html, "<title>", "</title>");
  const description = between(html, 'name="description" content="', '"');
  if (!rawTitle || !description) throw new Error(`${page.file}: missing a title or a description to build from`);

  const next = applyTo(html, headBlock(page, decode(rawTitle.trim()), decode(description.trim())));
  if (next === html) continue;
  if (check) stale.push(page.file);
  else writeFileSync(page.file, next);
}

// robots.txt — one Sitemap line is what actually gets the sitemap found; the
// rest is politeness. Nothing is disallowed because nothing here is private:
// the whole site is thirteen pages meant to be read.
const robots = `# ${ORIGIN}
User-agent: *
Allow: /

# Superseded homepage explorations. Served so old links do not break, but they
# are duplicate copy and must never compete with the real pages in an index.
Disallow: /website-drafts/

Sitemap: ${ORIGIN}/sitemap.xml
`;

const today = new Date().toISOString().slice(0, 10);
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${PAGES.map(
  (page) => `  <url>
    <loc>${ORIGIN}${page.path}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${page.changefreq}</changefreq>
    <priority>${page.priority}</priority>
  </url>`,
).join("\n")}
</urlset>
`;

for (const [file, content] of [
  ["robots.txt", robots],
  ["sitemap.xml", sitemap],
]) {
  const current = (() => {
    try {
      return readFileSync(file, "utf8");
    } catch {
      return null;
    }
  })();
  // lastmod changes daily; only the shape of the file matters for --check.
  const same = current !== null && current.replace(/<lastmod>[^<]*<\/lastmod>/g, "") === content.replace(/<lastmod>[^<]*<\/lastmod>/g, "");
  if (same) continue;
  if (check) stale.push(file);
  else writeFileSync(file, content);
}

if (check) {
  if (stale.length) {
    console.error(`Out of date — run "node scripts/build-seo.mjs":\n  ${stale.join("\n  ")}`);
    process.exit(1);
  }
  console.log("SEO metadata is up to date.");
} else {
  console.log(`Wrote SEO metadata into ${PAGES.length} pages, plus robots.txt and sitemap.xml.`);
}
