/**
 * The site's Content-Security-Policy, as a meta tag.
 *
 * GitHub Pages serves static files and cannot set a response header, so a meta
 * tag is the only mechanism available here. It is not the same thing:
 * `frame-ancestors` and `X-Frame-Options` are **ignored** in a meta tag, so
 * there is no clickjacking protection on this site and cannot be until it sits
 * behind something that sets headers. SECURITY.md records that.
 *
 * What it does buy: an injected script from any origin other than the three
 * named below will not run, a form cannot be repointed at somebody else's
 * server, `<base>` cannot be rewritten to redirect every relative link, and no
 * plugin content can be embedded at all.
 *
 * What remains permissive, and why:
 * - `'unsafe-inline'` on scripts, because contact.html carries an inline block.
 * - `'unsafe-inline'` on styles, because the markup carries style attributes.
 *
 * What used to be here and is not any more: `'unsafe-eval'`, cdn.tailwindcss.com
 * and unpkg.com. The Tailwind Play CDN compiled classes in the browser, which is
 * what `'unsafe-eval'` was granted for, and unpkg served an unpinned `lucide@latest`
 * for five icons on one page. Both are gone — Preflight is assets/base.css, the
 * utilities are the last block of assets/site.css, and the icons are inline SVG —
 * so the policy no longer has to name a host it cannot vouch for. A CSP naming a
 * third party does not protect against that third party; the fix was to stop
 * needing one. Nothing outside this origin may execute a script now.
 *
 * `style-src` and `font-src` no longer name fonts.googleapis.com or
 * fonts.gstatic.com, and that absence is load-bearing rather than tidying: the
 * typefaces are served from this origin now (assets/fonts.css), because a
 * <link> to Google Fonts sends every visitor's IP address to a US company
 * before the page paints, with no consent asked and no way to refuse. Leaving
 * the hosts in the policy would let that request quietly return. If either
 * host ever needs to come back, the privacy policy has to change with it.
 *
 * googletagmanager.com and google-analytics.com are still named, but nothing
 * reaches them until a visitor turns analytics on: assets/analytics.js is
 * gated behind assets/consent.js. A CSP entry is permission for a request that
 * the code may make, not proof that it makes one.
 */
const CSP = [
  "default-src 'self'",
  "base-uri 'self'",
  "object-src 'none'",
  "form-action 'self'",
  "script-src 'self' 'unsafe-inline' https://www.googletagmanager.com",
  "style-src 'self' 'unsafe-inline'",
  "font-src 'self' data:",
  "img-src 'self' data: https://www.googletagmanager.com https://www.google-analytics.com",
  // os.dakyx.com serves the product prices this site prints. The number is
  // already in the markup and correct; the request only replaces it when the
  // office has moved it since the last publish. No credentials are sent, and
  // the endpoint is above the OS's session middleware, so none could be read.
  "connect-src 'self' https://os.dakyx.com https://www.google-analytics.com https://www.googletagmanager.com",
  "frame-src 'none'",
  "upgrade-insecure-requests",
].join("; ");

function headBlock(page, title, description, faq) {
  const url = `${ORIGIN}${page.path}`;
  const json = JSON.stringify(schemaFor(page, title, description, faq), null, 2);
  const isArticle = Boolean(page.article);

  return [
    BEGIN,
    `<meta http-equiv="Content-Security-Policy" content="${attr(CSP)}">`,
    `<link rel="canonical" href="${url}">`,
    // A transactional page has nothing to offer a search result and should not
    // compete with the page that sells the thing. `noindex` pages are also kept
    // out of the sitemap and disallowed in robots.txt, so all three agree.
    page.noindex
      ? `<meta name="robots" content="noindex, nofollow">`
      : `<meta name="robots" content="index, follow, max-image-preview:large, max-snippet:-1, max-video-preview:-1">`,
    `<meta name="keywords" content="${attr(page.keywords)}">`,
    `<meta name="author" content="${COMPANY.name}">`,
    `<meta name="geo.region" content="GH-AH">`,
    `<meta name="geo.placename" content="${COMPANY.locality}">`,
    ...(VERIFICATION.google ? [`<meta name="google-site-verification" content="${attr(VERIFICATION.google)}">`] : []),
    ...(VERIFICATION.bing ? [`<meta name="msvalidate.01" content="${attr(VERIFICATION.bing)}">`] : []),
    ...(VERIFICATION.yandex ? [`<meta name="yandex-verification" content="${attr(VERIFICATION.yandex)}">`] : []),
    ...(VERIFICATION.naver ? [`<meta name="naver-site-verification" content="${attr(VERIFICATION.naver)}">`] : []),
    ``,
    `<meta property="og:type" content="${isArticle ? "article" : "website"}">`,
    ...(isArticle
      ? [
          `<meta property="article:published_time" content="${page.article.published}">`,
          `<meta property="article:section" content="${attr(page.article.section)}">`,
          `<meta property="article:publisher" content="${ORIGIN}/">`,
        ]
      : []),
    `<meta property="og:site_name" content="${COMPANY.name}">`,
    `<meta property="og:locale" content="en_GB">`,
    `<meta property="og:url" content="${url}">`,
    `<meta property="og:title" content="${attr(title)}">`,
    `<meta property="og:description" content="${attr(description)}">`,
    `<meta property="og:image" content="${SHARE_IMAGE}">`,
    `<meta property="og:image:width" content="1200">`,
    `<meta property="og:image:height" content="630">`,
    `<meta property="og:image:type" content="image/png">`,
    `<meta property="og:image:alt" content="${attr(SHARE_IMAGE_ALT)}">`,
    ``,
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:title" content="${attr(title)}">`,
    `<meta name="twitter:description" content="${attr(description)}">`,
    `<meta name="twitter:image" content="${SHARE_IMAGE}">`,
    `<meta name="twitter:image:alt" content="${attr(SHARE_IMAGE_ALT)}">`,
    ``,
    `<script type="application/ld+json">`,
    json,
    `</script>`,
    ``,
    `<!-- Cookie consent. Must be parsed before analytics.js, which asks it for -->`,
    `<!-- permission and does nothing at all if it is not there. -->`,
    `<link rel="stylesheet" href="/assets/consent.css">`,
    `<script src="/assets/consent.js" defer></script>`,
    `<!-- Does nothing until the GA4 Measurement ID is filled in at the top of -->`,
    `<!-- that file, and nothing then until the visitor allows analytics. -->`,
    `<script src="/assets/analytics.js" defer></script>`,
    END,
  ].join("\n");
}

/** Everything this generator owns is inside the markers, plus the old stray canonical it replaces. */
function applyTo(html, block) {
  let next = html;

  const begin = next.indexOf(BEGIN);
  if (begin !== -1) {
    const end = next.indexOf(END, begin);
    next = next.slice(0, begin) + block + next.slice(end + END.length);
    return next;
  }

  // First run: drop any hand-written canonical, then insert after the title.
  next = next.replace(/^[ \t]*<link rel="canonical"[^>]*>\r?\n/m, "");
  const titleEnd = next.indexOf("</title>");
  if (titleEnd === -1) throw new Error("no <title> to anchor to");
  const at = titleEnd + "</title>".length;
  return `${next.slice(0, at)}\n${block}${next.slice(at)}`;
}

