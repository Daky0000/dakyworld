/* Imported by build-breadcrumbs.mjs for the trails, which must be the same
   table the JSON-LD is built from. Importing a module runs it, so everything
   below happens only when this file is the program being run. */
const RUN_DIRECTLY = import.meta.url === pathToFileURL(process.argv[1] ?? "").href;
if (RUN_DIRECTLY) {

const check = process.argv.includes("--check");
const stale = [];

for (const page of PAGES) {
  const html = readFileSync(page.file, "utf8");
  const rawTitle = between(html, "<title>", "</title>");
  const description = between(html, 'name="description" content="', '"');
  if (!rawTitle || !description) throw new Error(`${page.file}: missing a title or a description to build from`);

  const next = applyTo(html, headBlock(page, decode(rawTitle.trim()), decode(description.trim()), readFaq(html)));
  if (next === html) continue;
  if (check) stale.push(page.file);
  else writeFileSync(page.file, next);
}

// robots.txt — one Sitemap line is what actually gets the sitemap found; the
// rest is politeness. Almost nothing is disallowed, because almost nothing here
// is private: the site is thirteen pages meant to be read.
const robots = `# ${ORIGIN}
User-agent: *
Allow: /

# Superseded homepage explorations. Served so old links do not break, but they
# are duplicate copy and must never compete with the real pages in an index.
Disallow: /website-drafts/

# The way in to the website editor. Not secret — it holds nothing but a link to
# the sign-in — but it is not a page anybody should reach from a search result.
Disallow: /admin

# An internal architecture document that was published to the site root by
# accident. Left in place so any link to it still resolves, but it is not a
# page of this website and must not be indexed as one. It also carries a
# noindex of its own — this rule stops it being crawled at all, the meta tag
# covers a crawler that reaches it by a route other than this file.
Disallow: /AGENT_SYSTEM_PLAN.html

${PAGES.filter((page) => page.noindex)
  .map(
    (page) => `
# ${page.noindexReason ?? "Not a page anybody should reach from a search result."}
Disallow: ${page.path}`,
  )
  .join("")}

# AI search and assistant crawlers, named so the welcome is explicit rather
# than inferred. A crawler that finds a group naming it ignores the * group
# entirely, which is why the same Disallow lines are repeated here. Being
# crawled by these is how the site gets cited in ChatGPT search, Claude,
# Perplexity, Copilot, Gemini and Google AI Overviews. The plain-text brief
# for them is ${ORIGIN}/llms.txt.
${AI_CRAWLERS.map((agent) => `User-agent: ${agent}`).join("\n")}
Allow: /
Disallow: /website-drafts/
Disallow: /admin
Disallow: /AGENT_SYSTEM_PLAN.html
${PAGES.filter((page) => page.noindex).map((page) => `Disallow: ${page.path}`).join("\n")}

Sitemap: ${ORIGIN}/sitemap.xml
`;

const today = new Date().toISOString().slice(0, 10);
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${PAGES.filter((page) => !page.noindex).map(
  (page) => `  <url>
    <loc>${ORIGIN}${page.path}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${page.changefreq}</changefreq>
    <priority>${page.priority}</priority>
  </url>`,
).join("\n")}
</urlset>
`;

for (const [file, content] of [
  ["robots.txt", robots],
  ["sitemap.xml", sitemap],
]) {
  const current = (() => {
    try {
      // CRLF on a Windows checkout (core.autocrlf), LF from this script: the
      // same file either way, so compare it as one.
      return readFileSync(file, "utf8").replace(/\r\n/g, "\n");
    } catch {
      return null;
    }
  })();
  // lastmod changes daily; only the shape of the file matters for --check.
  const same = current !== null && current.replace(/<lastmod>[^<]*<\/lastmod>/g, "") === content.replace(/<lastmod>[^<]*<\/lastmod>/g, "");
  if (same) continue;
  if (check) stale.push(file);
  else writeFileSync(file, content);
}

if (check) {
  if (stale.length) {
    console.error(`Out of date — run "node scripts/build-seo.mjs":\n  ${stale.join("\n  ")}`);
    process.exit(1);
  }
  console.log("SEO metadata is up to date.");
} else {
  console.log(`Wrote SEO metadata into ${PAGES.length} pages, plus robots.txt and sitemap.xml.`);
}
}
