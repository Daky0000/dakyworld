#!/usr/bin/env node
/**
 * Puts a visible breadcrumb at the top of every page except the homepage.
 *
 * The trail is read from the same table `build-seo.mjs` uses for the
 * `BreadcrumbList` in each page's JSON-LD, so the two cannot disagree — which
 * matters, because a BreadcrumbList describing a trail that does not exist on
 * the page is the kind of structured data Google treats as misleading rather
 * than helpful.
 *
 * Placement is hero-aware, because the two hero systems sit on opposite sides
 * of `<main>`. The six `.portal-hero` pages close their hero *before* `<main>`,
 * so the crumb goes straight inside it. The six `.hero--center` pages open
 * `<main>` *with* the hero, so anchoring there would put the crumb above a
 * full-bleed dark section and directly under the fixed header — which is where
 * it landed on the first run, and looked exactly as wrong as it sounds.
 *
 * Either way the result is the same: cream, between the dark hero and the first
 * content section.
 *
 *   node scripts/build-breadcrumbs.mjs
 *   node scripts/build-breadcrumbs.mjs --check
 */

import { readFileSync, writeFileSync } from "node:fs";

const BEGIN = "<!-- BEGIN BREADCRUMB — generated by scripts/build-breadcrumbs.mjs -->";
const END = "<!-- END BREADCRUMB -->";

/** Same trails as PAGES in build-seo.mjs. Home is prepended; the last crumb is the page itself. */
const TRAILS = {
  "about.html": [["About", "/about"]],
  "services.html": [["Services", "/services"]],
  "work.html": [["Work", "/work"]],
  "how-we-work.html": [["How We Work", "/how-we-work"]],
  "pricing.html": [["Pricing", "/pricing"]],
  "monthly-support.html": [["Pricing", "/pricing"], ["Monthly Partnerships", "/monthly-support"]],
  "one-time-projects.html": [["Pricing", "/pricing"], ["One-Time Projects", "/one-time-projects"]],
  "foundation-build.html": [
    ["Pricing", "/pricing"],
    ["One-Time Projects", "/one-time-projects"],
    ["Website & Digital Foundation Build", "/foundation-build"],
  ],
  "insights.html": [["Insights", "/insights"]],
  "contact.html": [["Contact", "/contact"]],
  "privacy.html": [["Privacy", "/privacy"]],
  "terms.html": [["Terms", "/terms"]],
};

const escape = (text) => text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function markup(trail) {
  const crumbs = [["Home", "/"], ...trail];
  const items = crumbs
    .map(([name, href], index) =>
      index === crumbs.length - 1
        ? `      <li><span aria-current="page">${escape(name)}</span></li>`
        : `      <li><a href="${href}">${escape(name)}</a></li>`,
    )
    .join("\n");

  return [
    BEGIN,
    `<nav class="breadcrumb" aria-label="Breadcrumb">`,
    `  <div class="wrap">`,
    `    <ol>`,
    items,
    `    </ol>`,
    `  </div>`,
    `</nav>`,
    END,
  ].join("\n");
}

/** The index just past `<main id="main">`, or past the hero section when main opens with one. */
function insertionPoint(html, file) {
  const anchor = '<main id="main">';
  const at = html.indexOf(anchor);
  if (at === -1) throw new Error(`${file}: no <main id="main"> to anchor to`);
  let cursor = at + anchor.length;

  const heroAt = html.slice(cursor).search(/^\s*<section class="hero\b/);
  if (heroAt !== 0) return cursor;

  // Walk to the </section> that closes the hero, counting nested ones rather
  // than taking the first — a hero with a nested section would otherwise cut
  // the page in half.
  const tags = /<section\b|<\/section>/g;
  tags.lastIndex = cursor;
  let depth = 0;
  let match;
  while ((match = tags.exec(html))) {
    depth += match[0] === "</section>" ? -1 : 1;
    if (depth === 0) return match.index + match[0].length;
  }
  throw new Error(`${file}: the hero section is never closed`);
}

const check = process.argv.includes("--check");
const stale = [];

for (const [file, trail] of Object.entries(TRAILS)) {
  const html = readFileSync(file, "utf8");
  const block = markup(trail);
  let next;

  const begin = html.indexOf(BEGIN);
  if (begin !== -1) {
    // Re-place rather than edit in situ, so a corrected anchor actually moves it.
    const end = html.indexOf(END, begin);
    const stripped = (html.slice(0, begin) + html.slice(end + END.length)).replace(/\n{3,}/g, "\n\n");
    const at = insertionPoint(stripped, file);
    next = `${stripped.slice(0, at)}\n\n${block}\n${stripped.slice(at).replace(/^\n+/, "")}`;
  } else {
    // The hand-written one on foundation-build, with its inline styles and its
    // `.html` links, is replaced rather than duplicated.
    const base = html.replace(/[ \t]*<nav class="breadcrumb"[\s\S]*?<\/nav>\r?\n?/, "");
    const at = insertionPoint(base, file);
    next = `${base.slice(0, at)}\n\n${block}\n${base.slice(at).replace(/^\n+/, "")}`;
  }

  if (next === html) continue;
  if (check) stale.push(file);
  else writeFileSync(file, next);
}

if (check) {
  if (stale.length) {
    console.error(`Out of date — run "node scripts/build-breadcrumbs.mjs":\n  ${stale.join("\n  ")}`);
    process.exit(1);
  }
  console.log("Breadcrumbs are up to date.");
} else {
  console.log(`Wrote breadcrumbs into ${Object.keys(TRAILS).length} pages.`);
}
