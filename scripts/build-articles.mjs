#!/usr/bin/env node
/**
 * Turns `blog/*.md` into the article pages linked from /insights.
 *
 * The nine posts existed as cards on insights.html for months — with a
 * category, a read time and a date on each — and none of them was a link,
 * because none of them had ever been written. A card that says "6 min read ·
 * Aug 2026" and goes nowhere is a promise the site was not keeping, so the
 * posts are real now and this is what builds them.
 *
 * Why a generator rather than nine hand-written pages: the header, the footer,
 * the stylesheet list and the script tags would be nine more copies of markup
 * that already exists eleven times. Here they are read out of insights.html at
 * build time, so the nav gains a link in one place and every article follows.
 *
 * What this script owns is the region between the ARTICLE markers, and on a
 * page it is creating for the first time, the shell around them. It never
 * touches the SEO or BREADCRUMB blocks — those belong to the other two
 * generators, which run after this one:
 *
 *   node scripts/build-articles.mjs          # write blog/*.html from blog/*.md
 *   node scripts/build-articles.mjs --check  # fail if anything is out of date
 */

import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const SOURCE_DIR = "blog";
const SHELL_PAGE = "insights.html";
const BEGIN = "<!-- BEGIN ARTICLE — generated by scripts/build-articles.mjs from the .md beside this file -->";
const END = "<!-- END ARTICLE -->";

// --- the front matter and the body -------------------------------------------

/**
 * `key: value` lines, then a blank line, then the post.
 *
 * Deliberately not YAML: four keys do not need a parser, and a dependency in a
 * repo whose website has no build step is a cost every future reader pays.
 */
function parse(text, file) {
  const normalised = text.replace(/\r\n/g, "\n");
  const split = normalised.indexOf("\n\n");
  if (split === -1) throw new Error(`${file}: no blank line between the front matter and the post`);

  const meta = {};
  for (const line of normalised.slice(0, split).split("\n")) {
    const at = line.indexOf(":");
    if (at === -1) throw new Error(`${file}: "${line}" is not a key: value line`);
    meta[line.slice(0, at).trim()] = line.slice(at + 1).trim();
  }

  for (const key of ["title", "description", "section", "published", "summary", "order", "category", "tone"]) {
    if (!meta[key]) throw new Error(`${file}: missing "${key}" in the front matter`);
  }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(meta.published)) throw new Error(`${file}: published must be YYYY-MM-DD`);

  return { meta, body: normalised.slice(split + 2).trim() };
}

const escape = (text) => text.replace(/&(?!#?\w+;)/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/** Bold, italic, inline code and links — the four things the posts actually use. */
function inline(text) {
  return escape(text)
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>')
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
    .replace(/(^|[\s(])\*([^*]+)\*/g, "$1<em>$2</em>")
    .replace(/`([^`]+)`/g, "<code>$1</code>");
}

/**
 * A deliberately small Markdown: `##` and `###` headings, paragraphs, `-` and
 * `1.` lists, and `>` pull quotes. Anything else is a paragraph, which is the
 * right failure: a post renders as prose rather than as markup nobody meant.
 */
function render(body) {
  const out = [];
  const blocks = body.split(/\n{2,}/);

  for (const block of blocks) {
    const lines = block.split("\n").filter((line) => line.trim());
    if (!lines.length) continue;

    if (/^###\s+/.test(lines[0])) {
      out.push(`<h3>${inline(lines[0].replace(/^###\s+/, ""))}</h3>`);
      continue;
    }
    if (/^##\s+/.test(lines[0])) {
      out.push(`<h2>${inline(lines[0].replace(/^##\s+/, ""))}</h2>`);
      continue;
    }
    if (lines.every((line) => /^>\s?/.test(line))) {
      out.push(`<blockquote><p>${inline(lines.map((line) => line.replace(/^>\s?/, "")).join(" "))}</p></blockquote>`);
      continue;
    }
    if (lines.every((line) => /^[-*]\s+/.test(line))) {
      const items = lines.map((line) => `  <li>${inline(line.replace(/^[-*]\s+/, ""))}</li>`).join("\n");
      out.push(`<ul>\n${items}\n</ul>`);
      continue;
    }
    if (lines.every((line) => /^\d+\.\s+/.test(line))) {
      const items = lines.map((line) => `  <li>${inline(line.replace(/^\d+\.\s+/, ""))}</li>`).join("\n");
      out.push(`<ol>\n${items}\n</ol>`);
      continue;
    }
    out.push(`<p>${inline(lines.join(" "))}</p>`);
  }

  return out.join("\n\n");
}

/** Words of prose, for the reading time and the `wordCount` in the schema. */
const countWords = (body) => body.replace(/[#>*`\-\[\]()]/g, " ").split(/\s+/).filter(Boolean).length;

/** 200 words a minute, never less than a minute, so the figure on the card is arrived at rather than chosen. */
export const readingMinutes = (body) => Math.max(1, Math.round(countWords(body) / 200));

const LONG_DATE = (iso) =>
  new Date(`${iso}T00:00:00Z`).toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" });

/* Spelled out rather than taken from `toLocaleDateString`, whose en-GB short
   month for September is "Sept" — four letters where every other month has
   three, which reads as a typo on a row of cards. */
const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const SHORT_DATE = (iso) => `${MONTHS[Number(iso.slice(5, 7)) - 1]} ${iso.slice(0, 4)}`;

// --- the shell ----------------------------------------------------------------

/**
 * The parts of a page that are the same on every page, taken from a real one.
 *
 * Read from insights.html rather than kept in a template file here, because a
 * template file is a second copy of the header: the day somebody adds a nav
 * link to eleven pages, the articles would be the twelfth that nobody
 * remembers. This way they cannot fall behind.
 */
function shell() {
  const html = readFileSync(SHELL_PAGE, "utf8").replace(/\r\n/g, "\n");
  const headStart = html.indexOf("<!-- BEGIN SEO");
  const headEnd = html.indexOf("</head>");
  const afterSeo = html.indexOf("<!-- END SEO -->") + "<!-- END SEO -->".length;
  const header = html.slice(html.indexOf("<body>"), html.indexOf("<main id=\"main\">"));
  const footer = html.slice(html.indexOf("<footer>"), html.indexOf("</body>") + "</body>".length);
  if (headStart === -1 || headEnd === -1 || !header || !footer) throw new Error(`${SHELL_PAGE}: could not read the shell out of it`);
  return { headTail: html.slice(afterSeo, headEnd), header, footer };
}

// --- a page -------------------------------------------------------------------

function articleMarkup(meta, body, minutes) {
  return [
    BEGIN,
    `<article class="article-page">`,
    `  <div class="wrap">`,
    `    <div class="article-head">`,
    `      <div class="eyebrow">${escape(meta.section)}</div>`,
    `      <h1 class="display">${inline(meta.title)}</h1>`,
    `      <p class="article-standfirst">${inline(meta.summary)}</p>`,
    `      <p class="article-byline"><time datetime="${meta.published}">${LONG_DATE(meta.published)}</time> &middot; ${minutes} min read &middot; Dakyworld</p>`,
    `    </div>`,
    `    <div class="article-prose">`,
    render(body)
      .split("\n")
      .map((line) => (line ? `      ${line}` : line))
      .join("\n"),
    `    </div>`,
    `    <aside class="article-next">`,
    `      <h2>Is this the shape of something in your business?</h2>`,
    `      <p>If any of this sounds like the week your team is having, a thirty-minute conversation is usually enough to tell whether it is worth doing anything about.</p>`,
    `      <a href="/contact" class="btn btn-primary">Book a consultation &rarr;</a>`,
    `      <a href="/insights" class="link">All insights &rarr;</a>`,
    `    </aside>`,
    `  </div>`,
    `</article>`,
    END,
  ].join("\n");
}

function page(existing, meta, body, minutes, parts) {
  const article = articleMarkup(meta, body, minutes);

  if (existing) {
    const begin = existing.indexOf(BEGIN);
    if (begin === -1) throw new Error("an existing article page with no ARTICLE markers — delete it and rebuild");
    const end = existing.indexOf(END, begin);
    return existing.slice(0, begin) + article + existing.slice(end + END.length);
  }

  // First build: the head carries only what the page itself owns. The SEO
  // block, and the breadcrumb, are written by the generators that run next.
  return [
    "<!DOCTYPE html>",
    '<html lang="en">',
    "<head>",
    '<meta charset="UTF-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1.0">',
    '<meta name="theme-color" content="#08101f">',
    `<meta name="description" content="${escape(meta.description)}">`,
    /* The brand suffix only if it fits. Every other page on the site ends
       "| Dakyworld®", but a post's headline is already 50-odd characters and
       a search result truncates around 60 — at which point the suffix costs
       the end of the actual title and buys nothing. */
    `<title>${inline(meta.title)}${meta.title.length <= 48 ? " | Dakyworld&reg;" : ""}</title>`,
    parts.headTail.trim(),
    "</head>",
    parts.header.replace("<body>", "<body>").trimEnd(),
    '<main id="main">',
    "",
    article,
    "",
    "</main>",
    "",
    parts.footer,
    "</html>",
    "",
  ].join("\n");
}

// --- run ----------------------------------------------------------------------

const check = process.argv.includes("--check");
const stale = [];

/* build-seo.mjs imports `articles` for the page table, and importing a module
   runs it — so reading the posts happens on import, and writing files happens
   only when this file is the program. Without the guard, `node
   scripts/build-seo.mjs --check` would rewrite the article pages it was asked
   to check. */
const RUN_DIRECTLY = import.meta.url === pathToFileURL(process.argv[1] ?? "").href;

/** What insights.html needs to know about each post, in the order they are listed. */
export const articles = readdirSync(SOURCE_DIR)
  .filter((file) => file.endsWith(".md"))
  .map((file) => {
    const slug = file.replace(/\.md$/, "");
    const { meta, body } = parse(readFileSync(join(SOURCE_DIR, file), "utf8"), file);
    return { slug, meta, body, minutes: readingMinutes(body), words: countWords(body), path: `/blog/${slug}` };
  })
  /* `order` rather than the filename, so the slug stays a readable URL and the
     nine cards on /insights keep the sequence they were listed in. */
  .sort((a, b) => Number(a.meta.order) - Number(b.meta.order));

const parts = RUN_DIRECTLY || check ? shell() : null;

if (RUN_DIRECTLY) {
for (const article of articles) {
  const target = join(SOURCE_DIR, `${article.slug}.html`);
  const existing = existsSync(target) ? readFileSync(target, "utf8") : null;
  const next = page(existing?.replace(/\r\n/g, "\n") ?? null, article.meta, article.body, article.minutes, parts);
  if (existing && next === existing.replace(/\r\n/g, "\n")) continue;
  if (check) stale.push(target);
  else writeFileSync(target, next);
}

// --- the cards on /insights --------------------------------------------------

/**
 * The nine cards are written from the same nine posts.
 *
 * They used to be hand-written markup, which is how they came to advertise a
 * read time and a month for posts that did not exist and could not be clicked:
 * "5 min read · Apr 2026" on a card with an arrow and no link. Generated, a
 * card cannot outlive its article or disagree with it about the date, and a
 * tenth post adds a tenth card with no edit here.
 */
const GRID_BEGIN = "<!-- BEGIN ARTICLE CARDS — generated by scripts/build-articles.mjs -->";
const GRID_END = "<!-- END ARTICLE CARDS -->";

function cards(eol) {
  return articles
    .map((article, index) =>
      [
        `      <article class="article reveal" data-category="${escape(article.meta.category)}">`,
        `        <a class="article-link" href="${article.path}">`,
        `          <div class="article-image ${escape(article.meta.tone)}"><div class="article-icon">${String(index + 1).padStart(2, "0")}</div></div>`,
        `          <div class="article-body">`,
        `            <div class="article-category">${escape(article.meta.section)}</div>`,
        `            <h3 class="display">${inline(article.meta.title)}</h3>`,
        `            <p>${inline(article.meta.summary)}</p>`,
        `            <div class="article-meta"><span>${article.minutes} min read &middot; <time datetime="${article.meta.published}">${SHORT_DATE(article.meta.published)}</time></span><span class="article-arrow" aria-hidden="true">&rarr;</span></div>`,
        `          </div>`,
        `        </a>`,
        `      </article>`,
      ].join(eol),
    )
    .join(eol + eol);
}

{
  const html = readFileSync(SHELL_PAGE, "utf8");
  const eol = html.includes("\r\n") ? "\r\n" : "\n";
  const block = [GRID_BEGIN, cards(eol), GRID_END].join(eol);
  const OPEN = '<div class="article-grid">';

  const begin = html.indexOf(GRID_BEGIN);
  let next;
  if (begin !== -1) {
    next = html.slice(0, begin) + block + html.slice(html.indexOf(GRID_END) + GRID_END.length);
  } else {
    // First run: everything inside `.article-grid` is replaced, including the
    // dates and read times that were never true.
    const open = html.indexOf(OPEN);
    if (open === -1) throw new Error(`${SHELL_PAGE}: no ${OPEN} to write the cards into`);
    const from = open + OPEN.length;
    const close = html.indexOf(`${eol}    </div>`, from);
    if (close === -1) throw new Error(`${SHELL_PAGE}: the article grid is never closed`);
    next = html.slice(0, from) + eol + eol + block + html.slice(close);
  }

  if (next !== html) {
    if (check) stale.push(SHELL_PAGE);
    else writeFileSync(SHELL_PAGE, next);
  }
}

if (check) {
  if (stale.length) {
    console.error(`Out of date — run "node scripts/build-articles.mjs":\n  ${stale.join("\n  ")}`);
    process.exit(1);
  }
  console.log("Article pages are up to date.");
} else {
  console.log(`Wrote ${articles.length} article pages into ${SOURCE_DIR}/.`);
}
}

export { SHORT_DATE };
